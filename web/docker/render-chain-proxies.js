const fs = require('fs');

const outputPath = process.argv[2] || '/etc/nginx/conf.d/chain-proxies.conf';

function readChainConfigs() {
  const raw = process.env.CHAIN_CONFIGS;
  if (!raw || !raw.trim()) {
    return [];
  }
  const parsed = JSON.parse(raw);
  if (!Array.isArray(parsed)) {
    throw new Error('CHAIN_CONFIGS must be a JSON array');
  }
  return parsed;
}

function requireChainId(chain, index) {
  if (!Number.isInteger(chain.chainId) || chain.chainId <= 0) {
    throw new Error(`CHAIN_CONFIGS[${index}].chainId must be a positive integer`);
  }
  return chain.chainId;
}

function readUrl(chain, index, field) {
  const value = chain[field];
  if (typeof value !== 'string' || !value.trim()) {
    throw new Error(`CHAIN_CONFIGS[${index}].${field} is required`);
  }
  const parsed = new URL(value);
  if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:') {
    throw new Error(`CHAIN_CONFIGS[${index}].${field} must be an http(s) URL`);
  }
  return value.trim();
}

function readEnvUrl(field) {
  const value = process.env[field];
  if (typeof value !== 'string' || !value.trim()) {
    throw new Error(`${field} is required`);
  }
  const parsed = new URL(value);
  if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:') {
    throw new Error(`${field} must be an http(s) URL`);
  }
  return value.trim();
}

function readOptionalEnvUrl(field) {
  const value = process.env[field];
  if (value === undefined || !value.trim()) {
    return undefined;
  }
  return readEnvUrl(field);
}

function readChainRelayerUrl(chain, index, legacyRelayerUrl) {
  if (chain.relayerUrl !== undefined && chain.relayerUrl !== null && chain.relayerUrl !== '') {
    return readUrl(chain, index, 'relayerUrl');
  }
  if (legacyRelayerUrl) {
    return legacyRelayerUrl;
  }
  throw new Error(`CHAIN_CONFIGS[${index}].relayerUrl is required when RELAYER_URL is unset`);
}

function nginxEscape(value) {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

function renderProxyBlock(kind, chainId, upstream) {
  if (kind === 'api') {
    return `
    location ~ ^/api/chain/${chainId}/(.*)$ {
        set $relayer_url "${nginxEscape(upstream)}";
        proxy_pass $relayer_url/$1$is_args$args;
        proxy_http_version 1.1;
        proxy_set_header Host $proxy_host;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_buffering off;
        proxy_read_timeout 60s;
        proxy_send_timeout 60s;
    }
`;
  }
  return `
    location = /rpc/chain/${chainId} {
        set $rpc_url "${nginxEscape(upstream)}";
        proxy_pass $rpc_url;
        proxy_http_version 1.1;
        proxy_ssl_server_name on;
        proxy_ssl_name $proxy_host;
        proxy_set_header Host $proxy_host;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_buffering off;
        proxy_read_timeout 30s;
    }
`;
}

const chains = readChainConfigs();
const seen = new Set();
const legacyRelayerUrl = readOptionalEnvUrl('RELAYER_URL');
const validatorServiceUrl = readEnvUrl('VALIDATOR_SERVICE_URL');
let output = `# Generated by docker/render-chain-proxies.js from CHAIN_CONFIGS.
    location = /validator {
        set $validator_url "${nginxEscape(validatorServiceUrl)}";
        proxy_pass $validator_url/validator;
        proxy_http_version 1.1;
        proxy_set_header Host $proxy_host;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_buffering off;
        proxy_read_timeout 60s;
    }

    location ^~ /admin/ {
        set $validator_url "${nginxEscape(validatorServiceUrl)}";
        proxy_pass $validator_url$request_uri;
        proxy_http_version 1.1;
        proxy_set_header Host $proxy_host;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header Authorization $http_authorization;
        proxy_buffering off;
        proxy_read_timeout 60s;
        proxy_send_timeout 60s;
    }
`;
for (const [index, chain] of chains.entries()) {
  const chainId = requireChainId(chain, index);
  if (seen.has(chainId)) {
    throw new Error(`CHAIN_CONFIGS must not contain duplicate chainId ${chainId}`);
  }
  seen.add(chainId);
  output += renderProxyBlock('api', chainId, readChainRelayerUrl(chain, index, legacyRelayerUrl));
  output += renderProxyBlock('rpc', chainId, readUrl(chain, index, 'rpcUrl'));
}

fs.writeFileSync(outputPath, output);
